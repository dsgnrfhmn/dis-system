#!/usr/bin/env python3
"""Self-host Libre Bodoni (SIL OFL 1.1) italic, variable weight 400-700.

Fetches the Google Fonts CSS, downloads every woff2 subset it lists into
fonts/, and writes fonts/libre-bodoni.css with @font-face rules that point at
the local files (unicode-range kept, so a browser loads only the subsets a
page needs). Run once from the repo root; needs network, stdlib only:

    python3 scripts/fetch_fonts.py
"""
import pathlib
import re
import urllib.request

CSS_URL = "https://fonts.googleapis.com/css2?family=Libre+Bodoni:ital,wght@1,400..700&display=swap"
# A modern UA makes Google answer with woff2 instead of ttf.
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36"

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "fonts"
out.mkdir(exist_ok=True)


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


css = get(CSS_URL).decode("utf-8")
blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S)
if not blocks:
    raise SystemExit("no @font-face blocks found in the Google Fonts CSS")

rules = []
for subset, block in blocks:
    url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
    name = f"LibreBodoni-Italic-{subset}.woff2"
    (out / name).write_bytes(get(url))
    block = re.sub(r"url\(https://[^)]+\.woff2\)", f'url("{name}")', block)
    rules.append(f"/* {subset} */\n{block}\n")
    print("wrote", out / name)

header = (
    "/* GENERATED by scripts/fetch_fonts.py -- do not edit by hand.\n"
    "   Libre Bodoni Italic, variable weight 400-700, SIL Open Font License 1.1.\n"
    "   Self-hosted: the host app is local-network only and loads no CDN. */\n"
)
(out / "libre-bodoni.css").write_text(header + "\n".join(rules))
print("wrote", out / "libre-bodoni.css")
