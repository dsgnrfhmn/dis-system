#!/usr/bin/env python3
"""Self-host the dashboard's webfonts (all SIL OFL 1.1).

For each family below it fetches the Google Fonts CSS, downloads every woff2
subset it lists into fonts/, and writes fonts/<name>.css with @font-face rules
that point at the local files (unicode-range kept, so a browser loads only the
subsets a page needs). Run once from the repo root; needs network, stdlib only:

    python3 scripts/fetch_fonts.py

Families:
  libre-bodoni   Libre Bodoni Italic, variable weight 400-700 (hero title)
  bodoni-moda    Bodoni Moda Bold 700 (portfolio and CV sheet titles)
  karla          Karla Light 300 and Medium 500 (sheet text and captions)
"""
import pathlib
import re
import urllib.request

# A modern UA makes Google answer with woff2 instead of ttf.
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36"

# (css name, Google Fonts CSS URL, file stem, description for the header,
#  subsets to keep: None = all, file name part from the block's weight/style)
FAMILIES = [
    ("libre-bodoni",
     "https://fonts.googleapis.com/css2?family=Libre+Bodoni:ital,wght@1,400..700&display=swap",
     "LibreBodoni-Italic", "Libre Bodoni Italic, variable weight 400-700", None),
    ("bodoni-moda",
     "https://fonts.googleapis.com/css2?family=Bodoni+Moda:wght@700&display=swap",
     "BodoniModa", "Bodoni Moda Bold 700 (latin, latin-ext)", {"latin", "latin-ext"}),
    ("karla",
     "https://fonts.googleapis.com/css2?family=Karla:wght@300;500&display=swap",
     "Karla", "Karla Light 300 and Medium 500 (latin, latin-ext, vietnamese)",
     {"latin", "latin-ext", "vietnamese"}),
]

root = pathlib.Path(__file__).resolve().parent.parent
out = root / "fonts"
out.mkdir(exist_ok=True)


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read()


for css_name, css_url, stem, description, keep in FAMILIES:
    css = get(css_url).decode("utf-8")
    blocks = re.findall(r"/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})", css, re.S)
    if not blocks:
        raise SystemExit(f"no @font-face blocks found for {css_name}")
    rules = []
    for subset, block in blocks:
        if keep is not None and subset not in keep:
            continue
        url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
        weight = re.search(r"font-weight:\s*(\d+)\s*;", block)
        # A static family has one file per weight and subset; the variable italic one per subset.
        part = "" if css_name == "libre-bodoni" else f"-{weight.group(1)}"
        name = f"{stem}{part}-{subset}.woff2"
        (out / name).write_bytes(get(url))
        block = re.sub(r"url\(https://[^)]+\.woff2\)", f'url("{name}")', block)
        rules.append(f"/* {subset} */\n{block}\n")
        print("wrote", out / name)
    header = (
        "/* GENERATED by scripts/fetch_fonts.py -- do not edit by hand.\n"
        f"   {description}, SIL Open Font License 1.1.\n"
        "   Self-hosted: the host app is local-network only and loads no CDN. */\n"
    )
    (out / f"{css_name}.css").write_text(header + "\n".join(rules))
    print("wrote", out / f"{css_name}.css")
