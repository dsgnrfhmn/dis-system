#!/usr/bin/env python3
"""Compose Jinja2 template fragments into static HTML pages.

Mirrors tokens/build.py's role for the token pipeline: components/*/
template.html is the source of truth for a component's real, reusable
markup; component authors never hand-copy another component's HTML into
their own -- they {% include %} its template.html instead, declaring the
dependency in that component's own meta.json "uses" field.

Two modes:

  python scripts/compose.py
      Default. For every components/<name>/ (except TEMPLATE, which has a
      placeholder meta.json build_manifest.py also skips), composes
      demo.html -- hand-authored, includes this component's own
      template.html (and, for real composition, other components'
      template.html) -- into components/<name>/index.html. index.html is
      the only file this script ever writes in this mode; template.html,
      demo.html, style.css, component.js and meta.json are read-only
      inputs. index.html is GENERATED -- never hand-edit it after this
      migration; edit demo.html and rerun this script instead.

      Sibling style.css/component.js links for every component in this
      component's "uses" closure (transitive, topologically ordered,
      dependencies before dependents, self last) are appended to the
      composed output for any that demo.html didn't already link by hand
      -- see inject_assets(). A demo-only pairing with a component that
      isn't a real "uses" dependency (e.g. dropdown-menu's demo pairing
      with input-dropdown -- see that component's own demo.html) needs no
      entry in "uses" and gets no automatic injection; link its assets by
      hand in demo.html, as that file already does.

  python scripts/compose.py --pages <dir> --output <dir>
      For an external consumer project (e.g. one that vendors this design
      system as a git submodule and writes its own pages against these
      components' template.html files). Composes every *.html file found
      under <dir> (recursively) and writes it to the mirrored path under
      <output>, which is never the same as <dir> and is never written to
      unless explicitly passed. No asset auto-injection in this mode --
      a consumer page is a complete page of its own and links its own
      assets.

Before composing anything, in either mode, this script validates the
*entire* components/*/ "uses" graph -- every component's meta.json "uses"
list is cross-checked against the real {% include %} calls found in that
component's own template.html (jinja2.meta.find_referenced_templates, not
a regex scan of the source: this reads Jinja's own parsed template AST for
static include targets, which is the accurate way to answer "what does
this template.html actually include" without writing a template parser of
our own). An include found but not declared in "uses", or a name declared
in "uses" but never actually included, fails the build and names the file
and the mismatched dependency. The same graph is then checked for cycles.
Both checks run before any file is composed or written -- a broken
dependency graph never produces partial output.

Deterministic: the Jinja2 Environment is configured for stable whitespace
handling (trim_blocks/lstrip_blocks) and every ordering decision in this
script (topological sort, asset injection, directory walks) is a pure
function of the on-disk *.json/*.html inputs -- rerunning against
unchanged input reproduces byte-identical output, which is what keeps a
consumer project's post-rebuild git diff clean.
"""

import argparse
import json
import re
import sys
from pathlib import Path

import jinja2
from jinja2 import meta as jinja_meta

ROOT = Path(__file__).resolve().parent.parent
COMPONENTS_DIR = ROOT / "components"
TEMPLATE_INCLUDE_RE = re.compile(r"^components/([a-z][a-z0-9-]*)/template\.html$")

LINK_RE = re.compile(r'<link\s+rel="stylesheet"\s+href="([^"]+)"\s*/?>')
SCRIPT_RE = re.compile(r'<script\s+src="([^"]+)"\s*></script>')

GENERATED_HEADER = (
    "<!-- GENERATED by scripts/compose.py from demo.html -- do not edit by "
    "hand, edit demo.html and rerun the script instead. -->\n"
)


SAFE_URL_RE = re.compile(r"^(?:[a-z][a-z0-9+.-]*:)", re.IGNORECASE)
SAFE_URL_SCHEMES = ("http:", "https:", "mailto:", "tel:")


def safe_url(value):
    """Jinja filter for href/src props: passes relative URLs, fragments and
    http(s)/mailto/tel through, replaces any other scheme (javascript:,
    data:, vbscript:, ...) with "#". Whitespace and control characters are
    stripped before the check, since browsers ignore them in a scheme."""
    if value is None:
        return value
    probe = re.sub(r"[\x00-\x20]", "", str(value)).lower()
    if SAFE_URL_RE.match(probe) and not probe.startswith(SAFE_URL_SCHEMES):
        return "#"
    return value


def make_env(root=ROOT, extra_roots=None):
    """Autoescape is on: every prop is text unless a template marks it
    `| safe`. Only `extra_attrs` is marked so -- it is raw attribute
    markup written by the page author, never data from end users."""
    roots = [str(root)] + [str(r) for r in (extra_roots or [])]
    env = jinja2.Environment(
        loader=jinja2.FileSystemLoader(roots),
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        undefined=jinja2.Undefined,
        autoescape=True,
    )
    env.filters["safe_url"] = safe_url
    return env


def discover_components(components_dir=COMPONENTS_DIR):
    """Return {name: {"dir": Path, "meta": dict}} for every real component
    (skips TEMPLATE, matching scripts/build_manifest.py's own precedent --
    its meta.json carries placeholder values like category:
    "REPLACE_WITH_CATEGORY" that would fail schema validation)."""
    components = {}
    for meta_path in sorted(components_dir.glob("*/meta.json")):
        component_dir = meta_path.parent
        if component_dir.name == "TEMPLATE":
            continue
        meta = json.loads(meta_path.read_text())
        components[component_dir.name] = {"dir": component_dir, "meta": meta}
    return components


def find_template_includes(env, template_rel_path):
    """Names of components whose template.html this template.html
    statically {% include %}s, per Jinja's own parsed AST."""
    source = env.loader.get_source(env, template_rel_path)[0]
    ast = env.parse(source)
    included = set()
    for ref in jinja_meta.find_referenced_templates(ast):
        if ref is None:
            continue
        match = TEMPLATE_INCLUDE_RE.match(ref)
        if match:
            included.add(match.group(1))
    return included


def build_and_validate_uses_graph(env, components):
    """Returns (graph, errors). graph maps name -> [declared uses], in the
    order meta.json's own "uses" array declares them (deduplicated) --
    topo_closure()'s traversal order depends on this being a list, not a
    set: Python's per-string hash randomization makes set() iteration
    order vary run to run, which would make composed output
    non-deterministic. errors is non-empty if any component's declared
    "uses" doesn't match its template.html's actual includes."""
    graph = {}
    errors = []
    for name, info in sorted(components.items()):
        declared_list = list(dict.fromkeys(info["meta"].get("uses", [])))
        declared = set(declared_list)
        graph[name] = declared_list
        template_path = info["dir"] / "template.html"
        if not template_path.exists():
            errors.append(f"components/{name}/template.html: file does not exist")
            continue
        rel_path = f"components/{name}/template.html"
        actual = find_template_includes(env, rel_path)
        for undeclared in sorted(actual - declared):
            errors.append(
                f"components/{name}/template.html includes "
                f"components/{undeclared}/template.html, but "
                f'components/{name}/meta.json "uses" does not list '
                f'"{undeclared}" -- add it, or remove the include if it '
                f"was demo-only illustration (that belongs in demo.html, "
                f"not template.html)."
            )
        for dead in sorted(declared - actual):
            errors.append(
                f'components/{name}/meta.json "uses" lists "{dead}", but '
                f"components/{name}/template.html never includes "
                f"components/{dead}/template.html -- remove it from "
                f'"uses", or add the include if it was dropped by mistake.'
            )
    return graph, errors


def find_cycle(graph):
    """DFS cycle search over the declared "uses" graph. Returns the cycle
    as a list of names (first repeated at the end) or None."""
    WHITE, GRAY, BLACK = 0, 1, 2
    color = {name: WHITE for name in graph}
    path = []

    def visit(name):
        color[name] = GRAY
        path.append(name)
        for dep in sorted(graph.get(name, ())):
            if dep not in graph:
                continue  # dangling dep already reported by validation
            if color[dep] == GRAY:
                cycle_start = path.index(dep)
                return path[cycle_start:] + [dep]
            if color[dep] == WHITE:
                found = visit(dep)
                if found:
                    return found
        path.pop()
        color[name] = BLACK
        return None

    for name in sorted(graph):
        if color[name] == WHITE:
            found = visit(name)
            if found:
                return found
    return None


def topo_closure(name, graph):
    """Transitive "uses" closure of `name`, topologically ordered
    (dependencies before dependents), not including `name` itself.
    Deterministic: follows each component's own "uses" list in the order
    meta.json declares it, depth-first."""
    order = []
    seen = set()

    def visit(n):
        for dep in graph.get(n, ()):
            if dep not in seen:
                seen.add(dep)
                visit(dep)
                order.append(dep)

    visit(name)
    return order


def required_assets(name, graph, components):
    """(css_hrefs, js_srcs): hrefs/srcs for this component's own style.css/
    component.js plus every component in its "uses" closure, topologically
    ordered (deps first, self last), skipping a component.js that doesn't
    exist on disk. Paths are relative to components/<name>/, matching the
    convention every hand-authored demo.html already uses."""
    component_dir = components[name]["dir"]
    deps = topo_closure(name, graph) + [name]
    css_hrefs = []
    js_srcs = []
    for dep in deps:
        dep_dir = components[dep]["dir"]
        rel = "style.css" if dep == name else f"../{dep}/style.css"
        css_hrefs.append(rel)
        js_path = dep_dir / "component.js"
        if js_path.exists():
            rel_js = "component.js" if dep == name else f"../{dep}/component.js"
            js_srcs.append(rel_js)
    return css_hrefs, js_srcs


def _resolve(component_dir, href):
    return (component_dir / href).resolve()


def inject_assets(html, css_hrefs, js_srcs, component_dir):
    """Append any required css/js link not already present in `html`
    (compared by the resolved on-disk path each href points at, not by
    exact string match, so "style.css" and "../popup/style.css" are
    correctly recognized as different targets), then dedup so nothing
    that demo.html already linked by hand is ever loaded twice -- loading
    a component.js twice would double-attach its own event listeners."""
    existing_css = {_resolve(component_dir, m.group(1)) for m in LINK_RE.finditer(html)}
    existing_js = {_resolve(component_dir, m.group(1)) for m in SCRIPT_RE.finditer(html)}

    missing_css = [h for h in css_hrefs if _resolve(component_dir, h) not in existing_css]
    missing_js = [s for s in js_srcs if _resolve(component_dir, s) not in existing_js]

    if missing_css:
        css_block = "\n".join(f'<link rel="stylesheet" href="{h}">' for h in missing_css)
        link_matches = list(LINK_RE.finditer(html))
        if link_matches:
            pos = link_matches[-1].end()
            html = html[:pos] + "\n" + css_block + html[pos:]
        else:
            html = css_block + "\n" + html

    if missing_js:
        js_block = "\n".join(f'<script src="{s}"></script>' for s in missing_js)
        script_matches = list(SCRIPT_RE.finditer(html))
        if script_matches:
            pos = script_matches[-1].end()
            html = html[:pos] + "\n" + js_block + html[pos:]
        else:
            html = html.rstrip("\n") + "\n" + js_block + "\n"

    html = tag_re_dedup(html, LINK_RE, component_dir)
    html = tag_re_dedup(html, SCRIPT_RE, component_dir)
    return html


def tag_re_dedup(html, tag_re, component_dir):
    seen = set()

    def replace(match):
        key = _resolve(component_dir, match.group(1))
        if key in seen:
            return ""
        seen.add(key)
        return match.group(0)

    return tag_re.sub(replace, html)


def compose_default(env, components, graph):
    written = 0
    for name, info in sorted(components.items()):
        demo_path = info["dir"] / "demo.html"
        if not demo_path.exists():
            print(f"error: components/{name}/demo.html does not exist", file=sys.stderr)
            sys.exit(1)
        template = env.get_template(f"components/{name}/demo.html")
        rendered = template.render()
        css_hrefs, js_srcs = required_assets(name, graph, components)
        rendered = inject_assets(rendered, css_hrefs, js_srcs, info["dir"])
        output_path = info["dir"] / "index.html"
        output_path.write_text(GENERATED_HEADER + rendered)
        written += 1
    return written


def compose_pages(env, pages_dir, output_dir):
    pages_dir = pages_dir.resolve()
    output_dir = output_dir.resolve()
    if output_dir in (pages_dir, *pages_dir.parents):
        print(
            "error: --output must not be --pages itself or an ancestor of it "
            "(it would overwrite input pages)",
            file=sys.stderr,
        )
        sys.exit(1)

    page_paths = sorted(pages_dir.rglob("*.html"))
    if not page_paths:
        print(f"error: no *.html files found under {pages_dir}", file=sys.stderr)
        sys.exit(1)

    written = 0
    for page_path in page_paths:
        rel = page_path.relative_to(pages_dir)
        source = page_path.read_text()
        template = env.from_string(source)
        rendered = template.render()
        out_path = output_dir / rel
        out_path.parent.mkdir(parents=True, exist_ok=True)
        out_path.write_text(rendered)
        written += 1
        print(f"wrote {out_path}")
    return written


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--pages", type=Path, help="external consumer pages directory")
    parser.add_argument("--output", type=Path, help="output directory for --pages mode")
    args = parser.parse_args()

    if bool(args.pages) != bool(args.output):
        parser.error("--pages and --output must be given together")

    components = discover_components()
    env = make_env(extra_roots=[args.pages] if args.pages else None)
    graph, errors = build_and_validate_uses_graph(env, components)
    if errors:
        print("compose: \"uses\" graph does not match real template.html includes:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        sys.exit(1)

    cycle = find_cycle(graph)
    if cycle:
        print("compose: circular \"uses\" dependency:", file=sys.stderr)
        print("  " + " -> ".join(cycle), file=sys.stderr)
        sys.exit(1)

    if args.pages:
        written = compose_pages(env, args.pages, args.output)
        print(f"composed {written} page(s) from {args.pages} to {args.output}")
    else:
        written = compose_default(env, components, graph)
        print(f"composed {written} component index.html file(s)")


if __name__ == "__main__":
    main()
